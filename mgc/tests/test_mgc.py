def _read(d, name):
    with open(os.path.join(d, name)) as f:
        return f.read()


def _hdr(d):
    return os.path.join(d, 'include', 'test.h')


def _c(d, name, src=None):
    return compile_source(src if src is not None else _read(d, name), name, _hdr(d))


def _body(c):
    # drop the banner line naming the source file
    return '\n'.join(l for l in c.splitlines() if not l.startswith('// Generated by mgc'))


def _code(c):
    # drop comments and blank lines (comments inside pipeline() bodies are not kept)
    return '\n'.join(l for l in _body(c).splitlines() if l.strip() and not l.strip().startswith('//'))


def _clang_format():
    for p in (shutil.which('clang-format'), os.path.join(REPO, 'llvm', 'install', 'bin', 'clang-format')):
        if p and os.access(p, os.X_OK):
            return p
    return None


class Golden(unittest.TestCase):
    """The committed tests are exactly what mgcc produces from their sources."""

    def check(self, d, name):
        if _clang_format() is None:
            self.skipTest('clang-format not available')
        out = subprocess.run([sys.executable, os.path.join(REPO, 'mgc', 'mgcc.py'), os.path.join(d, name)],
                             capture_output=True, text=True, check=True).stdout
        self.assertEqual(out, _read(d, os.path.join('src', 'test.c')))

    def test_mm_os(self):
        self.check(OS, 'mm_os.mgc')

    def test_mm_ws(self):
        self.check(WS, 'mm_ws.mgc')

    def test_mm_is(self):
        self.check(IS, 'mm_is.mgc')

    def test_mm_os_l1k(self):
        self.check(L1K, 'mm_os_l1k.mgc')


class Equivalence(unittest.TestCase):

    def test_os_pipelined_equals_explicit(self):
        self.assertEqual(_code(_c(OS, 'mm_os.mgc')), _code(_c(OS, 'mm_os_explicit.mgc')))

    def test_os_schedule_order(self):
        c = _c(OS, 'mm_os.mgc')
        # prologue: program job 0 while its operands load, start it once they landed
        pro = c[c.index('l2_addr_x,'):c.index('for (int i = 0')]
        order = ['l2_addr_x,', 'l2_addr_w,', 'mg_redmule_gemm_enqueue', '&idma_evt_x);', '&idma_evt_w);',
                 '&idma_evt_y);', 'mg_redmule_gemm_commit_start']
        self.assertEqual(order, sorted(order, key=pro.index))
        # step: prefetch + program job i+1, commit it behind job i, wait job i
        loop = c[c.index('if (i < (timeslots - 1))'):]
        order = ['l2_addr_x +', 'l2_addr_w +', 'mg_redmule_gemm_enqueue', '&idma_evt_x);', '&idma_evt_w);',
                 'mg_redmule_gemm_commit_start', 'redmule_evt_curr);']
        self.assertEqual(order, sorted(order, key=loop.index))
        # the hand-written shape: the current-job wait is in both branches
        self.assertEqual(loop.count('mg_redmule_wait(&eu_ctrl, WAIT_MODE, redmule_evt_curr);'), 2)
        self.assertNotIn('mg_redmule_gemm_start(', c)
        self.assertNotIn('mg_redmule_gemm_commit(', c)

    def test_ir_after_pipeline_has_no_pipeline(self):
        ir = print_ir(compile_module(_read(L1K, 'mm_os_l1k.mgc'), 'mm_os_l1k.mgc', _hdr(L1K), until='pipeline'))
        self.assertNotIn('mg.pipeline', ir)
        self.assertIn('mg.job', ir)  # kernel calls are lowered later, by job-lower


class Systolic(unittest.TestCase):

    def test_ws_stages_and_guards(self):
        c = _c(WS, 'mm_ws.mgc')
        self.assertIn('int pt = t - t_start;', c)
        self.assertIn('if (pt >= 0 && pt <= timeslots) {', c)
        for g in ('if (pt < (timeslots - 1)) {', 'if (pt > 0) {', 'if (pt < timeslots) {'):
            self.assertIn(g, c)
        # y is sent by the tile above: the job is committed one stage after the loads (valid
        # after the barrier), and waited in the same step (lag=0)
        enq = c.index('mg_redmule_gemm_enqueue')
        self.assertEqual(c[c.rfind('if (', 0, enq):].split('\n')[0], 'if (pt < timeslots) {')
        self.assertLess(c.index('mg_redmule_gemm_commit_start'), c.index('mg_redmule_wait(&eu_ctrl, WAIT_MODE, &redmule_evt);'))
        self.assertEqual(c.count('fsync_sync_global(&fsync_ctrl);'), 2)  # prologue + every step

    def test_remote_store_and_uniform_layout(self):
        c = _c(WS, 'mm_ws.mgc')
        self.assertIn('uint32_t l1_base_s = get_l1_base(hartid + MESH_X_TILES);', c)
        self.assertIn('l1_base_s + (y_pt_prev - l1_tile_base),', c)
        # every tile must lay out L1 identically: worst-case (max) tile sizes
        self.assertIn('l1_addr_x_0 = l1_addr_w + (tile_h_max * tile_w_max * 2);', c)
        # ...whereas without neighbour access the actual sizes are used (as in mm_os)
        self.assertIn('l1_addr_x_0 = l1_addr_y + (tile_h * tile_w * 2);', _c(OS, 'mm_os.mgc'))

    def test_is_east_and_row_barrier(self):
        c = _c(IS, 'mm_is.mgc')
        self.assertIn('uint32_t l1_base_e = get_l1_base(hartid + 1);', c)
        self.assertIn('fsync_sync_row(&fsync_ctrl);', c)
        self.assertNotIn('fsync_sync_global', c)

    def test_event_storage_split_only_when_overlapping(self):
        ws = _c(WS, 'mm_ws.mgc')  # y is loaded (top row) while the previous block is sent
        self.assertIn('idma_evt_y_in', ws)
        self.assertIn('idma_evt_y_out', ws)
        os_ = _c(OS, 'mm_os.mgc')  # y load and store never overlap
        self.assertIn('mg_event_t idma_evt_y, idma_evt_x, idma_evt_w;', os_)

    def test_explicit_ws_compiles_with_rotate_and_continue(self):
        c = _c(WS, 'mm_ws_explicit.mgc')
        i, j = c.index('3b. Select'), c.index('switch (pt % 3)')
        self.assertLess(i, j)
        self.assertIn('continue;', c)

    def test_depth_too_small(self):
        src = _read(WS, 'mm_ws.mgc').replace('Y[0:t_size, tile_w], depth=3', 'Y[0:t_size, tile_w], depth=2')
        with self.assertRaises(MgcError) as cm:
            _c(WS, 'x.mgc', src)
        self.assertIn('live across 3 pipeline stages', str(cm.exception))


class Kernels(unittest.TestCase):

    def test_core_call_and_prototype(self):
        c = _c(L1K, 'mm_os_l1k.mgc')
        self.assertIn('extern void l1_copy_fp16(uint32_t dst, uint32_t src, uint32_t p0);', c)
        self.assertIn('l1_copy_fp16(x_pt, x_raw_pt, tile_h * t_size);', c)

    def test_kernel_overlaps_previous_job(self):
        # job i is programmed before the CV32 copy that produces its input and committed
        # right after it; job i-1 runs meanwhile and is waited last
        c = _c(L1K, 'mm_os_l1k.mgc')
        loop = c[c.index('for (int i = 0'):]
        order = ['mg_redmule_gemm_enqueue', 'l1_copy_fp16(x_pt', 'mg_redmule_gemm_commit_start',
                 '&idma_evt_w);', 'redmule_evt_prev);']
        self.assertEqual(order, sorted(order, key=loop.index))

    def test_independent_commit_before_kernel(self):
        # a job that does not read the kernel's output is started before the CV32 call
        src = _read(L1K, 'mm_os_l1k.mgc').replace('redmule.enqueue(x[i], w[i], y,', 'redmule.enqueue(x_raw[i], w[i], y,')
        c = _c(L1K, 'x.mgc', src)
        loop = c[c.index('for (int i = 0'):]
        self.assertLess(loop.index('mg_redmule_gemm_commit_start'), loop.index('l1_copy_fp16(x_pt'))

    def test_kernel_operand_count(self):
        src = _read(L1K, 'mm_os_l1k.mgc').replace('copy(x[i], x_raw[i])', 'copy(x[i])')
        with self.assertRaises(MgcError) as cm:
            _c(L1K, 'x.mgc', src)
        self.assertIn('takes 2 L1 operands', str(cm.exception))

    def test_kernel_operands_must_be_l1(self):
        src = _read(L1K, 'mm_os_l1k.mgc').replace('copy(x[i], x_raw[i])', 'copy(x[i], X[tile_h, 0:t_size])')
        with self.assertRaises(MgcError) as cm:
            _c(L1K, 'x.mgc', src)
        self.assertIn('expected an L1 buffer', str(cm.exception))


class Extensibility(unittest.TestCase):
    """New iDMA modes and new HWPEs are descriptor changes only."""

    X3 = ('X3 = l2("x_inp", (M, 4, N // 4), fp16)\nZ = l2(', '        redmule_evt = redmule.events(2)')

    def _x3(self, alloc):
        s = _read(OS, 'mm_os_explicit.mgc').replace('Z = l2(', self.X3[0], 1).replace(
            self.X3[1], self.X3[1] + '\n        q = L1.single_buffer(' + alloc + ')\n        idma.load(q, ' + alloc + ').wait()', 1)
        return _c(OS, 'x.mgc', s)

    def test_rank_limit_from_capabilities(self):
        with self.assertRaises(MgcError) as cm:
            self._x3('X3[tile_h, 0:2, 0:t_size]')
        self.assertIn('at most 2-D', str(cm.exception))

    def test_3d_idma_is_a_table_change(self):
        caps = devices.IdmaCaps(max_rank=3, l1_strided=False,
                                functions={1: 'mg_idma_memcpy_1d', 2: 'mg_idma_memcpy_2d', 3: 'mg_idma_memcpy_3d'})
        with mock.patch.object(devices, 'IDMA', caps):
            c = self._x3('X3[tile_h, 0:2, 0:t_size]')
        self.assertIn('mg_idma_memcpy_3d(', c)
        self.assertIn('uint32_t std2_q = ', c)

    def test_contiguous_3d_is_1d(self):
        c = self._x3('X3[tile_h, 0:4, :]')
        self.assertIn('uint32_t len_q = tile_h * 4 * (N_SIZE / 4) * 2;', c)
        self.assertIn('(tile_h_max * y_id * 4 * (N_SIZE / 4) * 2)', c)

    def test_indexed_3d_is_2d(self):
        c = self._x3('X3[tile_h, 1, :]')
        self.assertIn('uint32_t len_q = N_SIZE / 4 * 2;', c)
        self.assertIn('uint32_t std_q = 4 * (N_SIZE / 4) * 2;', c)

    def test_new_hwpe_is_a_descriptor(self):
        acc = devices.Hwpe(
            name='neureka', ctrl='&neureka_ctrl', queue_depth=2,
            jobs={'scale': devices.HwpeJob(operands=(('a', 'in', 2), ('b', 'out', 2)),
                                           params=(('uint32_t', 'a.size'),),
                                           constraints=(('a.shape[0]', 'b.shape[0]'),
                                                        ('a.shape[1]', 'b.shape[1]')))},
            fn={'oneshot': 'mg_neureka_{job}', 'wait': 'mg_neureka_wait'})
        hw = dict(devices.HWPES, neureka=acc)
        # an asynchronous producer moves the RedMulE commit one stage later: w, x and the
        # RedMulE events live across one more stage
        src = _read(L1K, 'mm_os_l1k.mgc').replace('copy(x[i], x_raw[i])', 'neureka.scale(x_raw[i], x[i])').replace(
            'W[0:t_size, tile_w], depth=3', 'W[0:t_size, tile_w], depth=4').replace(
            'x = L1.multi_buffer(X[tile_h, 0:t_size], depth=2)', 'x = L1.multi_buffer(X[tile_h, 0:t_size], depth=3)').replace(
            'redmule.events(2)', 'redmule.events(3)')
        with mock.patch.dict(devices.HWPES, hw):
            c = _c(L1K, 'x.mgc', src)
            self.assertIn('mg_neureka_scale(&neureka_ctrl,', c)
            self.assertIn('(uint32_t)(tile_h * t_size)', c)
            self.assertIn('mg_neureka_wait(&eu_ctrl, WAIT_MODE, &neureka_evt);', c)
            bad = src.replace('neureka.scale(x_raw[i], x[i])', 'neureka.scale(x_raw[i], w[i])')
            with self.assertRaises(MgcError) as cm:
                _c(L1K, 'x.mgc', bad)
            self.assertIn('neureka.scale shapes do not match', str(cm.exception))


class Errors(unittest.TestCase):

    def assertError(self, old, new, msg, d=OS, src='mm_os_explicit.mgc'):
        s = _read(d, src)
        self.assertIn(old, s)
        with self.assertRaises(MgcError) as cm:
            _c(d, 'x.mgc', s.replace(old, new, 1))
        self.assertIn(msg, str(cm.exception))

    def test_strided_slice(self):
        self.assertError('X[tile_h, 0:t_size], depth=2', 'X[tile_h, 0:t_size:2], depth=2', 'unit step')

    def test_l1_to_l1(self):
        self.assertError('ey = idma.load(y, Y[tile_h, tile_w])', 'ey = idma.load(y, x[0])', 'L1->L1')

    def test_dma_shape_mismatch(self):
        self.assertError('ex = idma.load(x[0], X[tile_h, 0:t_size])',
                         'ex = idma.load(x[0], X[tile_h, 0:2 * t_size])', 'shape mismatch')

    def test_gemm_shape_mismatch(self):
        self.assertError('redmule.enqueue(x[0], w[0], y,', 'redmule.enqueue(w[0], x[0], y,', 'shapes do not match')

    def test_u8_overflow(self):
        self.assertError('timeslots: u8 = N_TIMESLOTS', 'timeslots: u8 = 4 * N', 'does not fit')

    def test_cores_reserved(self):
        self.assertError('for z in range(N_ITERATIONS):', 'for z in cores():', 'reserved')

    def test_nested_tiles(self):
        self.assertError('for z in range(N_ITERATIONS):', 'for z, zz in tiles():', 'outermost')

    def test_unwaited_event_reuse(self):
        self.assertError('            ex.wait()\n            ew.wait()\n            ey.wait()\n',
                         '            ew.wait()\n            ey.wait()\n'
                         '            ex = idma.load(x[1], X[tile_h, t_size:2 * t_size])\n',
                         'was not waited')

    def test_wait_never_issued(self):
        self.assertError('            ex.wait()\n            ew.wait()\n            ey.wait()\n',
                         '            ex.wait()\n            ex.wait()\n            ew.wait()\n            ey.wait()\n',
                         'never issued')

    def test_bad_slot_offset(self):
        self.assertError('ex = idma.load(x[i + 1],', 'ex = idma.load(x[i + 3],', '|k| < 2')

    def test_after_is_gone(self):
        self.assertError('job = redmule.gemm(x[pt], w, y[pt])', 'job = redmule.gemm(x[pt], w, y[pt], after=(ex,))',
                         'inferred', d=WS, src='mm_ws_explicit.mgc')

    def test_remote_load_rejected(self):
        self.assertError('idma.load(x[pt], X[pt * t_size:(pt + 1) * t_size, tile_h])',
                         'idma.load(x[pt], x.at_rel(1, 0)[pt])', 'L1->L1', d=WS, src='mm_ws.mgc')

    def test_unknown_size(self):
        self.assertError('sizes("M_SIZE", "N_SIZE", "K_SIZE")', 'sizes("M_SIZE", "N_SIZE", "Q_SIZE")',
                         'not #defined')


class RemoteTargets(unittest.TestCase):
    """L1 -> L1 stores to other tiles: relative, absolute, row/column multicast."""

    REL = 'idma.store(y.at_rel(1, 0)[pt], y[pt])'
    MCAST = '''from mgc import *

M, N, K = sizes("M_SIZE", "N_SIZE", "K_SIZE")
X = l2("x_inp", (M, N), fp16)
W = l2("w_inp", (N, K), fp16)
Y = l2("y_inp", (M, K), fp16)

@test("test_mcast")
def main():
    for y_id, x_id in tiles():
        tile_h = y_id.split(M)
        tile_w = x_id.split(K)
        x = L1.single_buffer(X[tile_h, :])
        w = L1.single_buffer(W[:, tile_w])
        y = L1.single_buffer(Y[tile_h, tile_w])
        if x_id == y_id:
            idma.load(x, X[tile_h, :]).wait()
            idma.store(x.row, x).wait()
        if y_id == 0:
            idma.load(w, W[:, tile_w]).wait()
            idma.store(w.col[0], w[0]).wait()
        sync(GLOBAL)
        idma.load(y, Y[tile_h, tile_w]).wait()
        redmule.gemm(x, w, y)
        idma.store(Y[tile_h, tile_w], y).wait()
'''

    def ws(self, new):
        src = _read(WS, 'mm_ws.mgc')
        self.assertIn(self.REL, src)
        return _c(WS, 'x.mgc', src.replace(self.REL, new))

    def test_absolute_tile(self):
        c = self.ws('idma.store(y.at(y_id + 1, x_id)[pt], y[pt])')
        self.assertIn('get_l1_base(GET_ID(y_id + 1, x_id)) + (y_pt_prev - l1_tile_base),', c)
        self.assertNotIn('l1_base_s', c)
        self.assertIn('l1_addr_x_0 = l1_addr_w + (tile_h_max * tile_w_max * 2);', c)  # uniform layout

    def test_row_and_col_multicast_lowered_to_unicasts(self):
        c = _c(OS, 'x.mgc', self.MCAST)
        self.assertIn('for (uint32_t mcast_x = 0; mcast_x < MESH_X_TILES; mcast_x++) {', c)
        self.assertIn('if (mcast_x != x_id) {', c)
        self.assertIn('get_l1_base(GET_ID(y_id, mcast_x)) + (l1_addr_x - l1_tile_base),', c)
        self.assertIn('for (uint32_t mcast_w = 0; mcast_w < MESH_Y_TILES; mcast_w++) {', c)
        self.assertIn('if (mcast_w != y_id) {', c)
        self.assertIn('get_l1_base(GET_ID(mcast_w, x_id)) + (l1_addr_w - l1_tile_base),', c)
        # one wait covers all the unicasts (same-direction transfers complete in order)
        self.assertEqual(c.count('mg_idma_wait(&eu_ctrl, 1, WAIT_MODE, &idma_evt_x);'), 1)
        self.assertIn('l1_addr_w = l1_addr_x + (tile_h_max * N_SIZE * 2);', c)  # uniform layout

    def test_native_multicast_is_a_table_change(self):
        caps = devices.IdmaCaps(max_rank=2, l1_strided=False, functions=devices.IDMA.functions,
                                multicast={'ROW': 'mg_idma_memcpy_row_mcast'})
        with mock.patch.object(devices, 'IDMA', caps):
            c = _c(OS, 'x.mgc', self.MCAST)
        self.assertNotIn('mcast_x', c)
        self.assertIn('mg_idma_memcpy_row_mcast(', c)
        self.assertIn('mcast_w < MESH_Y_TILES', c)  # COL is still lowered

    def test_multicast_slot_must_match(self):
        src = self.MCAST.replace('idma.store(w.col[0], w[0])', 'idma.store(x.col, w)')
        with self.assertRaisesRegex(MgcError, 'same buffer on another tile'):
            _c(OS, 'x.mgc', src)

    def test_multicast_is_not_a_load_source(self):
        src = self.MCAST.replace('idma.store(x.row, x)', 'idma.load(x, x.row)')
        with self.assertRaisesRegex(MgcError, 'L1->L1'):
            _c(OS, 'x.mgc', src)

    GATHER = '''from mgc import *

M, N, K = sizes("M_SIZE", "N_SIZE", "K_SIZE")

@test("test_gather")
def main():
    for y_id, x_id in tiles():
        tile_h = y_id.split(M)
        r = L1.single_buffer((tile_h,), fp16)
        rs = L1.single_buffer((MESH_X_TILES, tile_h), fp16)
        if x_id != 0:
            idma.store(rs.at(y_id, 0)[x_id, :], r).wait()
        sync(ROW)
'''

    def test_store_into_block_of_another_buffer(self):
        c = _c(OS, 'x.mgc', self.GATHER)
        self.assertIn('get_l1_base(GET_ID(y_id, 0)) + (l1_addr_rs + (x_id * tile_h * 2) - l1_tile_base),', c)
        self.assertIn('mg_idma_memcpy_1d(', c)
        self.assertIn('&idma_evt_r,', c)
        self.assertIn('l1_addr_rs = l1_addr_r + (tile_h_max * 2);', c)  # uniform layout

    def test_store_into_strided_block(self):
        src = (self.GATHER.replace('(tile_h,), fp16', '(tile_h, 4), fp16')
               .replace('(MESH_X_TILES, tile_h), fp16', '(tile_h, 16), fp16')
               .replace('[x_id, :]', '[:, 4:8]'))
        c = _c(OS, 'x.mgc', src)
        self.assertIn('(l1_addr_rs + (8) - l1_tile_base),', c)
        # 8 bytes per row, L1 stride 32 bytes, tile_h rows
        self.assertIn('l1_addr_r,\n                          8,\n                          32,\n'
                      '                          tile_h,', c)

    def test_store_into_block_multicast(self):
        c = _c(OS, 'x.mgc', self.GATHER.replace('rs.at(y_id, 0)[x_id, :]', 'rs.col[x_id, :]'))
        self.assertIn('get_l1_base(GET_ID(mcast_r, x_id)) + (l1_addr_rs + (x_id * tile_h * 2) - l1_tile_base),', c)

    def test_store_into_block_checks(self):
        with self.assertRaisesRegex(MgcError, 'shape mismatch'):
            _c(OS, 'x.mgc', self.GATHER.replace('[x_id, :]', '[x_id, 0:4]'))
        with self.assertRaisesRegex(MgcError, 'single-slot buffer'):
            _c(OS, 'x.mgc', self.GATHER.replace('rs = L1.single_buffer((MESH_X_TILES, tile_h), fp16)',
                                                'rs = L1.multi_buffer((MESH_X_TILES, tile_h), fp16, depth=2)'))

    def test_old_names_rejected(self):
        with self.assertRaisesRegex(MgcError, 'renamed `buf.at_rel'):
            self.ws('idma.store(y.on(1, 0)[pt], y[pt])')
        with self.assertRaisesRegex(MgcError, 'renamed `idma`'):
            self.ws('dma.store(y.at_rel(1, 0)[pt], y[pt])')


class TopFunction(unittest.TestCase):
    """`@top` emits a callable void function instead of a test `main`."""

    TEST_DECO = '@test("test_mm_os_mgc", authors=["Francesco Conti <f.conti@unibo.it>"])\ndef main():'

    def top(self, deco='@top', fname='my_gemm', drop_check=True):
        src = _read(OS, 'mm_os.mgc').replace(self.TEST_DECO, f'{deco}\ndef {fname}():')
        if drop_check:
            src = '\n'.join(l for l in src.splitlines() if not l.strip().startswith('check('))
        return src

    def test_top_emits_function(self):
        c = _c(OS, 'mm_os.mgc', self.top())
        self.assertIn('void my_gemm(void)', c)
        self.assertNotIn('int main', c)
        self.assertNotIn('test.h', c)
        self.assertNotIn('return 0', c)
        self.assertNotIn('return errors', c)
        self.assertIn('return;', c)  # tiles with no work exit early

    def test_top_with_authors(self):
        c = _c(OS, 'mm_os.mgc', self.top('@top(authors=["A B <a@b.c>"])'))
        self.assertIn('// A B <a@b.c>', c)

    def test_top_rejects_check(self):
        with self.assertRaisesRegex(MgcError, 'only available in @test'):
            _c(OS, 'mm_os.mgc', self.top(drop_check=False))

    def test_test_must_be_main(self):
        with self.assertRaisesRegex(MgcError, 'named `main`'):
            _c(OS, 'mm_os.mgc', self.top('@test("x")'))

    def test_undecorated_rejected(self):
        with self.assertRaisesRegex(MgcError, 'exactly one decorator'):
            _c(OS, 'mm_os.mgc', self.top('').replace('\n\ndef my_gemm', '\ndef my_gemm'))


